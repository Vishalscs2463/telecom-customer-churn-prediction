import streamlit as st
import pandas as pd
import numpy as np
from chart_utils import probability_gauge, COLORS
from model_loader import load_pipeline, model_missing_warning, THRESHOLD
from data_loader import get_model_feature_columns


def _build_input_df(inputs: dict) -> pd.DataFrame:
    """Convert form inputs to a single-row DataFrame matching training features."""
    row = {
        "Tenure Months":    inputs["tenure"],
        "Monthly Charges":  inputs["monthly_charges"],
        "Total Charges":    inputs["total_charges"],
        "Gender":           inputs["gender"],
        "Senior Citizen":   inputs["senior"],   # "Yes" / "No" (matches dataset)
        "Partner":          inputs["partner"],
        "Dependents":       inputs["dependents"],
        "Phone Service":    inputs["phone_service"],
        "Multiple Lines":   inputs["multiple_lines"],
        "Internet Service": inputs["internet_service"],
        "Online Security":  inputs["online_security"],
        "Online Backup":    inputs["online_backup"],
        "Device Protection": inputs["device_protection"],
        "Tech Support":     inputs["tech_support"],
        "Streaming TV":     inputs["streaming_tv"],
        "Streaming Movies": inputs["streaming_movies"],
        "Contract":         inputs["contract"],
        "Paperless Billing": inputs["paperless_billing"],
        "Payment Method":   inputs["payment_method"],
    }
    return pd.DataFrame([row])


def _retention_recommendation(prob: float, inputs: dict) -> tuple[str, str]:
    """Return (action_title, action_body) based on risk level and inputs."""
    if prob >= 0.33:
        # High risk — tailor advice
        tips = []
        if inputs["contract"] == "Month-to-month":
            tips.append("**Offer a discounted 1-year or 2-year contract** to lock in retention.")
        if inputs["internet_service"] == "Fiber optic":
            tips.append("**Proactively check service quality** — fiber optic customers show elevated churn.")
        if inputs["tech_support"] == "No" and inputs["internet_service"] != "No":
            tips.append("**Bundle a free Tech Support add-on** for the next 3 months.")
        if inputs["online_security"] == "No" and inputs["internet_service"] != "No":
            tips.append("**Offer a free Online Security trial** — customers with security services churn less.")
        if inputs["tenure"] < 12:
            tips.append("**Assign a dedicated onboarding specialist** — new customers are highest risk.")
        if not tips:
            tips.append("**Reach out with a personalised loyalty offer** (discount, upgrade, or added service).")
        return "🚨 Recommended Retention Actions", "\n\n".join(f"- {t}" for t in tips)
    else:
        return (
            "✅ Customer Appears Loyal",
            "- Continue standard service quality.\n"
            "- Consider a loyalty reward or early renewal discount to maintain satisfaction.\n"
            "- Monitor if circumstances change (e.g., contract nearing expiry)."
        )


def render(df, filters):
    st.markdown("## 🔮 Individual Customer Churn Prediction")
    st.markdown(
        "Enter a customer's details below to predict their churn probability using the "
        f"**Tuned Gradient Boosting model** (threshold = **{THRESHOLD}**).  \n"
        "The prediction is generated by your actual trained model — not a formula."
    )

    pipeline = load_pipeline()

    if pipeline is None:
        model_missing_warning()
        st.markdown("---")
        st.markdown(
            "**While the model file is missing**, you can still explore the form below. "
            "Once you export the model, predictions will be live."
        )

    # ── Input Form ────────────────────────────────────────────────────────────
    with st.form("prediction_form"):
        st.markdown("### 📝 Customer Details")

        # Row 1: Basic demographics
        c1, c2, c3, c4 = st.columns(4)
        with c1:
            gender = st.selectbox("Gender", ["Male", "Female"])
        with c2:
            senior = st.selectbox("Senior Citizen", ["No", "Yes"])
        with c3:
            partner = st.selectbox("Partner", ["No", "Yes"])
        with c4:
            dependents = st.selectbox("Dependents", ["No", "Yes"])

        # Row 2: Account details
        st.markdown("#### Account Information")
        c5, c6, c7 = st.columns(3)
        with c5:
            tenure = st.number_input(
                "Tenure (Months)", min_value=0, max_value=120, value=12,
                help="Number of months the customer has stayed."
            )
        with c6:
            monthly_charges = st.number_input(
                "Monthly Charges ($)", min_value=0.0, max_value=200.0, value=70.0, step=0.5
            )
        with c7:
            total_charges = st.number_input(
                "Total Charges ($)", min_value=0.0, max_value=10000.0,
                value=round(tenure * monthly_charges, 2), step=1.0,
                help="Leave as auto-calculated or enter the actual value."
            )

        # Row 3: Services
        st.markdown("#### Phone & Internet Services")
        c8, c9 = st.columns(2)
        with c8:
            phone_service = st.selectbox("Phone Service", ["Yes", "No"])
        with c9:
            multiple_lines = st.selectbox(
                "Multiple Lines", ["No", "Yes", "No phone service"]
            )

        c10, c11, c12 = st.columns(3)
        with c10:
            internet_service = st.selectbox("Internet Service", ["DSL", "Fiber optic", "No"])
        with c11:
            online_security = st.selectbox(
                "Online Security", ["No", "Yes", "No internet service"]
            )
        with c12:
            online_backup = st.selectbox(
                "Online Backup", ["No", "Yes", "No internet service"]
            )

        c13, c14, c15 = st.columns(3)
        with c13:
            device_protection = st.selectbox(
                "Device Protection", ["No", "Yes", "No internet service"]
            )
        with c14:
            tech_support = st.selectbox(
                "Tech Support", ["No", "Yes", "No internet service"]
            )
        with c15:
            streaming_tv = st.selectbox(
                "Streaming TV", ["No", "Yes", "No internet service"]
            )

        c16, _, _ = st.columns(3)
        with c16:
            streaming_movies = st.selectbox(
                "Streaming Movies", ["No", "Yes", "No internet service"]
            )

        # Row 4: Billing
        st.markdown("#### Billing & Contract")
        c17, c18, c19 = st.columns(3)
        with c17:
            contract = st.selectbox(
                "Contract", ["Month-to-month", "One year", "Two year"]
            )
        with c18:
            paperless_billing = st.selectbox("Paperless Billing", ["Yes", "No"])
        with c19:
            payment_method = st.selectbox(
                "Payment Method",
                [
                    "Electronic check",
                    "Mailed check",
                    "Bank transfer (automatic)",
                    "Credit card (automatic)",
                ],
            )

        submitted = st.form_submit_button(
            "🔮 Predict Customer Churn",
            use_container_width=True,
            type="primary",
        )

    # ── Prediction Result ─────────────────────────────────────────────────────
    if submitted:
        inputs = {
            "gender": gender, "senior": senior, "partner": partner,
            "dependents": dependents, "tenure": int(tenure),
            "monthly_charges": float(monthly_charges),
            "total_charges": float(total_charges),
            "phone_service": phone_service, "multiple_lines": multiple_lines,
            "internet_service": internet_service, "online_security": online_security,
            "online_backup": online_backup, "device_protection": device_protection,
            "tech_support": tech_support, "streaming_tv": streaming_tv,
            "streaming_movies": streaming_movies, "contract": contract,
            "paperless_billing": paperless_billing, "payment_method": payment_method,
        }

        input_df = _build_input_df(inputs)

        if pipeline is not None:
            prob = float(pipeline.predict_proba(input_df)[:, 1][0])
        else:
            # Fallback demo value
            prob = None
            st.error(
                "Model not loaded. Please run `export_model.py` and copy the `model/` folder here."
            )

        if prob is not None:
            will_churn = prob >= THRESHOLD
            risk_label = "🔴 HIGH RISK" if will_churn else "🟢 LOW RISK"
            risk_color = COLORS["churned"] if will_churn else COLORS["retained"]
            prediction_label = "Yes — Likely to Churn" if will_churn else "No — Likely to Stay"

            st.markdown("---")
            st.markdown("### 📊 Prediction Result")

            # Result banner
            st.markdown(
                f"""
                <div style="
                    background: {'linear-gradient(135deg,#E63946,#c1121f)' if will_churn else 'linear-gradient(135deg,#2DC653,#1a7d33)'};
                    border-radius: 12px; padding: 24px; text-align: center; color: white;
                    box-shadow: 0 4px 20px rgba(0,0,0,0.15); margin-bottom: 20px;
                ">
                    <div style="font-size:14px; letter-spacing:2px; opacity:0.9; font-weight:600;">PREDICTION</div>
                    <div style="font-size:36px; font-weight:800; margin: 8px 0;">{prediction_label}</div>
                    <div style="font-size:18px; opacity:0.9;">{risk_label}</div>
                </div>
                """,
                unsafe_allow_html=True,
            )

            # Gauge + details
            g_col, d_col = st.columns([1, 1])
            with g_col:
                st.plotly_chart(probability_gauge(prob), use_container_width=True)
            with d_col:
                st.markdown("#### Result Summary")
                st.metric("Churn Probability", f"{prob:.1%}")
                st.metric("Classification Threshold", f"{THRESHOLD:.0%}")
                st.metric("Predicted Churn", "Yes ⚠️" if will_churn else "No ✅")
                st.metric("Risk Category", "High Risk 🔴" if will_churn else "Low Risk 🟢")

                if will_churn:
                    if prob >= 0.65:
                        level = "Very High — immediate intervention recommended."
                    else:
                        level = "Moderate-High — prioritise outreach in next 7 days."
                else:
                    if prob < 0.15:
                        level = "Very Low — customer appears highly loyal."
                    else:
                        level = "Low — continue regular engagement."
                st.info(f"**Risk Assessment:** {level}")

            # Recommendations
            st.markdown("---")
            action_title, action_body = _retention_recommendation(prob, inputs)
            st.markdown(f"### {action_title}")
            st.markdown(action_body)

            # Input summary
            with st.expander("🗂️ View submitted customer profile"):
                display_df = input_df.T.reset_index()
                display_df.columns = ["Feature", "Value"]
                st.dataframe(display_df, use_container_width=True, hide_index=True)
